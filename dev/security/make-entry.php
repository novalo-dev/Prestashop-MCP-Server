declare(strict_types=1);

/*
 * Writes dev/security/entry.generated.php, the entry point Psalm's taint
 * analysis starts from.
 *
 * The MCP endpoint hands each tool what the assistant sent through a callable
 * stored in the registry, and a taint analysis cannot follow a call it only
 * learns about at run time. This file calls every handler directly with
 * request data, so Psalm treats a tool's $arguments as what they are: input
 * from outside. Generated, not kept by hand, so a new tool is never missed.
 *
 * Usage: php dev/security/make-entry.php [module root]
 */

$root = rtrim($argv[1] ?? dirname(__DIR__, 2), '/');
$lines = ['<?php', '// Generated by dev/security/make-entry.php - do not edit.'];

foreach (glob($root . '/tools/Somcp*.php') ?: [] as $file) {
    $class = basename($file, '.php');
    $lines[] = $class . '::handle($_POST, []);';
}

file_put_contents(__DIR__ . '/entry.generated.php', implode("\n", $lines) . "\n");
printf("%d tool handlers written to dev/security/entry.generated.php\n", count($lines) - 2);
